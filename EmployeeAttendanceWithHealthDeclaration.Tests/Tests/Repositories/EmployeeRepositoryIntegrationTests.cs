        [Fact]
        public async Task Delete_soft_deletes_by_csv_and_keeps_time_logs()
        {
            await using var connection = _fixture.CreateConnection();
            await IntegrationSeed.CreateProviderAsync(connection);
            await IntegrationSeed.CreateEmployeeAsync(connection, employee_id: "TST-000026");
            await IntegrationSeed.CreateEmployeeAsync(connection, employee_id: "TST-000027");
            var logId = await IntegrationSeed.CreateTimeLogAsync(connection, "TST-000026");
            var repo = new EmployeeRepository(connection);

            var result = await repo.Delete(new[] { "TST-000026", "TST-000027" });

            Assert.NotNull(result);
            Assert.True(result!.success);
            Assert.Equal(2, result.deleted_count);
            var flags = await connection.QueryAsync<(string employee_id, int is_deleted)>(
                "SELECT employee_id, is_deleted FROM employee WHERE employee_id IN ('TST-000026','TST-000027')");
            Assert.All(flags, f => Assert.Equal(1, f.is_deleted));
            // Attendance history is never touched by a employee soft delete.
            var logExists = await connection.ExecuteScalarAsync<int>(
                "SELECT COUNT(*) FROM time_logs WHERE attendance_id = @id", new { id = logId });
            Assert.Equal(1, logExists);
        }

