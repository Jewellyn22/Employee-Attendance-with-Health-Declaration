        private static employee NewEmployee(string name = "TST New Employee") => new()
        {
            name = name,
            gender = "Male",
            birthdate = DateTime.Today.AddYears(-28),
            contact_number = "09170000000",
            address = "TST Address",
            provider_code = IntegrationSeed.ProviderCode,
            active = 1,
            assignments = new List<employee_project_assignment>()
        };

        [Fact]
        public async Task Create_generates_provider_scoped_id_and_hydrates_assignment_aggregates()
        {
            await using var connection = _fixture.CreateConnection();
            await IntegrationSeed.CreateProviderAsync(connection);
            await IntegrationSeed.CreateProjectAsync(connection);
            var repo = new EmployeeRepository(connection);
            var submitted = NewEmployee();
            submitted.assignments!.Add(new employee_project_assignment
            {
                project_code = IntegrationSeed.ProjectCode,
                position = "Welder"
            });

            var created = await repo.Create(submitted);

            Assert.NotNull(created);
            // {provider_code}-NNNNNN, generated by the SP (first row for this fresh provider).
            Assert.Matches("^TST-\\d{6}$", created!.employee_id);
            Assert.Equal("TST", created.provider_code);
            Assert.Equal("TST Provider Co", created.provider_name);
            Assert.Equal(IntegrationSeed.ProjectCode, created.project_codes);
            Assert.Equal("Welder", created.positions);
            Assert.Contains(IntegrationSeed.ProjectCode, created.project_positions);
            Assert.Equal(1, created.active_project_count);
        }

        // PIN: assignments to nonexistent or wrong-provider projects are silently
        // dropped by the JSON_TABLE INNER JOIN — no error surfaces to the caller.
        [Fact]
        public async Task Create_silently_drops_wrong_provider_assignments()
        {
            await using var connection = _fixture.CreateConnection();
            await IntegrationSeed.CreateProviderAsync(connection);
            await IntegrationSeed.CreateProviderAsync(connection, provider_code: "TSTP-OTHER");
            await IntegrationSeed.CreateProjectAsync(connection, project_code: "TSTOP-26-001", provider_code: "TSTP-OTHER");
            var repo = new EmployeeRepository(connection);
            var submitted = NewEmployee();
            submitted.assignments!.Add(new employee_project_assignment
            {
                project_code = "TSTOP-26-001",   // belongs to a different provider
                position = "Welder"
            });

            var created = await repo.Create(submitted);

            Assert.NotNull(created);
            Assert.True(string.IsNullOrEmpty(created!.project_codes));   // zero rows -> NULL/empty GROUP_CONCAT
            Assert.Equal(0, created.active_project_count);
            var junctionRows = await connection.ExecuteScalarAsync<int>(
                "SELECT COUNT(*) FROM employee_project WHERE employee_id = @id",
                new { id = created.employee_id });
            Assert.Equal(0, junctionRows);   // PIN: silently dropped, not rejected
        }

