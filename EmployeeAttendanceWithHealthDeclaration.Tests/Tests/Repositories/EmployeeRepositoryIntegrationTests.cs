        [Fact]
        public async Task Update_rewrites_the_assignment_rows()
        {
            await using var connection = _fixture.CreateConnection();
            await IntegrationSeed.CreateProviderAsync(connection);
            await IntegrationSeed.CreateProjectAsync(connection, project_code: "TST-26-801");
            await IntegrationSeed.CreateProjectAsync(connection, project_code: "TST-26-802");
            await IntegrationSeed.CreateEmployeeAsync(connection, employee_id: "TST-000022");
            await IntegrationSeed.AssignProjectAsync(connection, "TST-000022", "TST-26-801");
            var repo = new EmployeeRepository(connection);
            var existing = await repo.GetByEmployeeId("TST-000022");

            existing!.assignments = new List<employee_project_assignment>
            {
                new() { project_code = "TST-26-802", position = "Supervisor" }
            };
            existing.name = "TST Renamed";
            var updated = await repo.Update(existing);

            var fetched = await repo.GetByEmployeeId("TST-000022");
            Assert.Equal("TST Renamed", fetched!.name);
            Assert.Equal("TST-26-802", fetched.project_codes);
            Assert.Equal("Supervisor", fetched.positions);
            var oldMapping = await connection.ExecuteScalarAsync<int>(
                "SELECT COUNT(*) FROM employee_project WHERE employee_id = 'TST-000022' AND project_code = 'TST-26-801'");
            Assert.Equal(0, oldMapping);   // delete-all + re-insert semantics
        }

