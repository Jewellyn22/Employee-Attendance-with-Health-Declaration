        [Fact]
        public async Task FindDuplicate_is_scoped_by_provider_and_birthdate()
        {
            await using var connection = _fixture.CreateConnection();
            await IntegrationSeed.CreateProviderAsync(connection);
            await IntegrationSeed.CreateProviderAsync(connection, provider_code: "TSTP-OTHER");
            var birthdate = new DateTime(1995, 6, 15);
            await IntegrationSeed.CreateEmployeeAsync(
                connection, employee_id: "TST-000024", name: "Maria Santos", birthdate: birthdate);
            var repo = new EmployeeRepository(connection);

            // Same person under a different provider -> NOT a duplicate.
            Assert.Null(await repo.FindDuplicate("TSTP-OTHER", "Maria Santos", birthdate));
            // Same name+provider but different birthdate -> NOT a duplicate.
            Assert.Null(await repo.FindDuplicate("TST", "Maria Santos", birthdate.AddDays(1)));
        }

