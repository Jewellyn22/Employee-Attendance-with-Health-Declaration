        [Fact]
        public async Task SetQrCode_stores_the_blob_and_GetQrCodes_returns_it()
        {
            await using var connection = _fixture.CreateConnection();
            await IntegrationSeed.CreateProviderAsync(connection);
            await IntegrationSeed.CreateEmployeeAsync(connection, employee_id: "TST-000029");
            var repo = new EmployeeRepository(connection);
            var png = QrCodeHelper.GeneratePng("TST-000029");

            var stored = await repo.SetQrCode("TST-000029", png);
            var fetched = (await repo.GetQrCodes()).ToList();

            Assert.True(stored);
            var row = Assert.Single(fetched, q => q.employee_id == "TST-000029");
            Assert.True(png.SequenceEqual(row.qr_code_image), "QR blob must round-trip byte-identical");
        }

        [Fact]
        public async Task SetInactive_deactivates_the_employee()
        {
            await using var connection = _fixture.CreateConnection();
            await IntegrationSeed.CreateProviderAsync(connection);
            await IntegrationSeed.CreateEmployeeAsync(connection, employee_id: "TST-000030");
            var repo = new EmployeeRepository(connection);

            var result = await repo.SetInactive("TST-000030");

            var active = await connection.ExecuteScalarAsync<int>(
                "SELECT active FROM employee WHERE employee_id = 'TST-000030'");
            Assert.Equal(0, active);
            Assert.True(result);
        }

        [Fact]
        public async Task GetActiveCount_counts_only_active_undeleted_employees()
        {
            await using var connection = _fixture.CreateConnection();
            await IntegrationSeed.CreateProviderAsync(connection);
            await IntegrationSeed.CreateEmployeeAsync(connection, employee_id: "TST-000031");            // active
            await IntegrationSeed.CreateEmployeeAsync(connection, employee_id: "TST-000032", active: 0); // inactive
            await IntegrationSeed.CreateEmployeeAsync(connection, employee_id: "TST-000033", is_deleted: 1); // deleted
            var repo = new EmployeeRepository(connection);
            var before = await repo.GetActiveCount();

            await IntegrationSeed.CreateEmployeeAsync(connection, employee_id: "TST-000034");            // +1 active

            var after = await repo.GetActiveCount();
            Assert.Equal(before + 1, after);   // delta-based assertion
        }
